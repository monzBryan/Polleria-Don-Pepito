type ProductSeed = Omit<Producto, 'categoriaId' | 'categoriaSlug' | 'categoriaNombre'> & {
  categoria: keyof typeof CAT;
};

function product(seed: ProductSeed): Producto {
  const cat = CAT[seed.categoria];
  return {
    ...seed,
    categoriaId: cat.id,
    categoriaSlug: cat.slug,
    categoriaNombre: cat.nombre,
  };
}

