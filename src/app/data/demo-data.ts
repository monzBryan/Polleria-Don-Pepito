function daysAgo(days: number, hour = 13, minute = 30): string {
  const date = new Date();
  date.setDate(date.getDate() - days);
  date.setHours(hour, minute, 0, 0);
  return date.toISOString();
}

function futureMinutes(minutes = 45): string {
  const date = new Date();
  date.setMinutes(date.getMinutes() + minutes);
  return date.toISOString();
}

function demoItem(productoId: number, cantidad: number, nota?: string) {
  const producto = DEMO_PRODUCTOS.find((p) => p.id === productoId);
  if (!producto) {
    throw new Error(`Producto demo no encontrado: ${productoId}`);
  }
  return {
    productoId: producto.id,
    nombre: producto.nombre,
    precioUnitario: producto.precio,
    cantidad,
    imagenUrl: producto.imagenUrl,
    nota,
  };
}

function seedPedido(
  id: string,
  codigo: string,
  perfilId: string,
  estado: Pedido['estado'],
  tipoEntrega: Pedido['tipoEntrega'],
  metodoPago: Pedido['metodoPago'],
  items: Pedido['items'],
  createdAt: string,
  extra: Partial<Pedido> = {},
): Pedido {
  const perfil = DEMO_PERFILES.find((p) => p.id === perfilId) ?? DEMO_PERFILES[1];
  const subtotal = items.reduce((acc, item) => acc + item.precioUnitario * item.cantidad, 0);
  const descuentoPuntos = extra.descuentoPuntos ?? 0;
  const costoDelivery =
    extra.costoDelivery ??
    (tipoEntrega === 'delivery' && subtotal < DEMO_CONFIG_WEB.freeDeliveryFrom
      ? DEMO_CONFIG_WEB.deliveryFee
      : 0);
  const puntosUsados = extra.puntosUsados ?? 0;
  const puntosGanados =
    extra.puntosGanados ?? Math.floor((subtotal - descuentoPuntos) * DEMO_CONFIG_PUNTOS.puntosPorSol);
  return {
    id,
    codigo,
    perfilId,
    clienteNombre: perfil.nombre,
    clienteEmail: perfil.email,
    clienteTelefono: perfil.telefono,
    tipoEntrega,
    direccion:
      tipoEntrega === 'delivery' ? extra.direccion ?? 'Av. Los Maestros 245, Ica' : undefined,
    referencia: extra.referencia,
    distrito: tipoEntrega === 'delivery' ? extra.distrito ?? 'Ica' : undefined,
    metodoPago,
    estado,
    items,
    subtotal,
    descuentoPuntos,
    costoDelivery,
    total: Math.max(0, subtotal - descuentoPuntos + costoDelivery),
    puntosUsados,
    puntosGanados: estado === 'cancelado' ? 0 : puntosGanados,
    notas: extra.notas,
    createdAt,
    updatedAt: extra.updatedAt ?? createdAt,
    fEntregaEstimada:
      extra.fEntregaEstimada ??
      (tipoEntrega === 'delivery' ? futureMinutes(45) : futureMinutes(20)),
  };
}

