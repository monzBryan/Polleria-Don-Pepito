   Adaptación a PostgreSQL / Supabase del archivo 02_TABLA_PUNTOS_SUPABASE.sql
   ----------------------------------------------------------------------------------
   Ejecutar después del modelo base (01_modelo_restaurante_postgres.sql).
   Estándar de auditoría: USUCRE, PCCRE, FECCRE, USUMOD, PCMOD, FECMOD, ESTADO
   Borrado lógico: ESTADO = 'A' Activo / 'I' Inactivo / 'E' Eliminado
   ----------------------------------------------------------------------------------
   REGLA DE NEGOCIO:
     - 1 Sol (PEN) gastado = 1 punto ganado (se acredita al confirmar la venta).
     - 100 puntos = 1 Sol de descuento en compras siguientes.
     - El canje se registra como movimiento 'USO' con puntos negativos.
   ================================================================================== */

/* ================================================================================
   01. CONFIGURACIÓN DE REGLAS DE PUNTOS
   ================================================================================ */
CREATE TABLE IF NOT EXISTS CONFIG_PUNTOS (
    ID_Config          int GENERATED BY DEFAULT AS IDENTITY,
    Puntos_Por_Sol     numeric(6,2)  NOT NULL DEFAULT 1.00,
    Puntos_X_Descuento int           NOT NULL DEFAULT 100,
    Valor_Descuento    numeric(8,2)  NOT NULL DEFAULT 1.00,
    Max_Descuento_Pct  numeric(5,2)  NOT NULL DEFAULT 50.00,
    puntos_Vencen      char(1)       NOT NULL DEFAULT 'N',
    Meses_Vencimiento  int           NULL,
    USUCRE             varchar(30)   NOT NULL DEFAULT current_user,
    PCCRE              varchar(30)   NULL DEFAULT 'supabase',
    FECCRE             timestamptz   NOT NULL DEFAULT now(),
    USUMOD             varchar(30)   NULL,
    PCMOD              varchar(30)   NULL,
    FECMOD             timestamptz   NULL,
    ESTADO             char(1)       NOT NULL DEFAULT 'A',
    CONSTRAINT PK_CONFIG_PUNTOS PRIMARY KEY (ID_Config),
    CONSTRAINT CK_CONFIGPUNTOS_POR CHECK (Puntos_Por_Sol > 0),
    CONSTRAINT CK_CONFIGPUNTOS_BLO CHECK (Puntos_X_Descuento > 0),
    CONSTRAINT CK_CONFIGPUNTOS_EST CHECK (ESTADO IN ('A','I','E'))
);

INSERT INTO CONFIG_PUNTOS (Puntos_Por_Sol, Puntos_X_Descuento, Valor_Descuento, USUCRE)
SELECT 1.00, 100, 1.00, 'admin'
WHERE NOT EXISTS (SELECT 1 FROM CONFIG_PUNTOS WHERE ESTADO = 'A');

/* ================================================================================
   02. TRANSACCION_PUNTOS : historial de movimientos de puntos por cliente
   ================================================================================ */
CREATE TABLE IF NOT EXISTS TRANSACCION_PUNTOS (
    ID_Transaccion     bigint GENERATED BY DEFAULT AS IDENTITY,
    ID_Cliente         int           NOT NULL,
    ID_Venta           int           NULL,
    Tipo_Movimiento    varchar(10)   NOT NULL,
    Puntos             int           NOT NULL,
    Monto_Afectado     numeric(12,2) NOT NULL DEFAULT 0,
    Saldo_Restante     int           NULL,
    Observacion        varchar(200)  NULL,
    USUCRE             varchar(30)   NOT NULL DEFAULT current_user,
    PCCRE              varchar(30)   NULL DEFAULT 'supabase',
    FECCRE             timestamptz   NOT NULL DEFAULT now(),
    USUMOD             varchar(30)   NULL,
    PCMOD              varchar(30)   NULL,
    FECMOD             timestamptz   NULL,
    ESTADO             char(1)       NOT NULL DEFAULT 'A',
    CONSTRAINT PK_TRANSACCION_PUNTOS PRIMARY KEY (ID_Transaccion),
    CONSTRAINT FK_TRAPTO_CLIENTE FOREIGN KEY (ID_Cliente) REFERENCES CLIENTE(ID_Cliente),
    CONSTRAINT FK_TRAPTO_VENTA   FOREIGN KEY (ID_Venta)   REFERENCES VENTA(ID_Venta),
    CONSTRAINT CK_TRAPTO_TIPO CHECK (Tipo_Movimiento IN ('GANANCIA','USO','AJUSTE','CADUCADO')),
    CONSTRAINT CK_TRAPTO_PTS  CHECK (Puntos <> 0),
    CONSTRAINT CK_TRAPTO_MTO  CHECK (Monto_Afectado >= 0),
    CONSTRAINT CK_TRAPTO_EST  CHECK (ESTADO IN ('A','I','E'))
);

CREATE INDEX IF NOT EXISTS IX_TRAPTO_CLIENTE ON TRANSACCION_PUNTOS(ID_Cliente)
    WHERE ESTADO <> 'E';
CREATE INDEX IF NOT EXISTS IX_TRAPTO_VENTA ON TRANSACCION_PUNTOS(ID_Venta)
    WHERE ESTADO <> 'E';

COMMENT ON TABLE TRANSACCION_PUNTOS IS
    'Movimientos de puntos de dinero virtual. 1 sol = 1 punto; 100 puntos = 1 sol de descuento.';

/* ================================================================================
   03. VISTA DE SALDO DE PUNTOS POR CLIENTE
   ================================================================================ */
CREATE OR REPLACE VIEW VW_PUNTOS_CLIENTE AS
SELECT
    c.ID_Cliente,
    COALESCE(trim(p.Nombre || ' ' || COALESCE(p.Ap_Paterno, '')), e.Razon_Social) AS N_Cliente,
    c.Puntos                       AS Puntos_Saldo,
    cp.Puntos_X_Descuento          AS Bloque_Canje,
    cp.Valor_Descuento             AS Valor_Bloque,
    floor(c.Puntos::numeric / cp.Puntos_X_Descuento) * cp.Valor_Descuento AS Descuento_Disponible_Soles
FROM CLIENTE c
LEFT JOIN PERSONA p   ON p.ID_Persona = c.ID_Persona
LEFT JOIN EMPRESA e   ON e.ID_Empresa = c.ID_Empresa
JOIN CONFIG_PUNTOS cp ON cp.ESTADO = 'A';

/* ================================================================================
   04. ACREDITAR PUNTOS GANADOS
   ================================================================================ */
CREATE OR REPLACE FUNCTION sp_acreditar_puntos(
    cliente_id int,
    venta_id   int DEFAULT NULL,
    monto      numeric(12,2) DEFAULT 0)
RETURNS int
LANGUAGE plpgsql
AS $$
DECLARE
    v_pct  numeric(6,2);
    v_pts  int;
    v_sal  int;
BEGIN
    SELECT Puntos_Por_Sol INTO v_pct FROM CONFIG_PUNTOS WHERE ESTADO = 'A';
    v_pts := floor(monto * v_pct);

    IF v_pts = 0 THEN
        RETURN 0;
    END IF;

    UPDATE CLIENTE
       SET Puntos  = Puntos + v_pts,
           USUMOD  = current_user,
           PCMOD   = left(COALESCE(inet_client_addr()::text, 'supabase'), 30),
           FECMOD  = now()
     WHERE ID_Cliente = cliente_id
    RETURNING Puntos INTO v_sal;

    IF v_sal IS NULL THEN
        RAISE EXCEPTION 'Cliente % no existe', cliente_id;
    END IF;

    INSERT INTO TRANSACCION_PUNTOS (ID_Cliente, ID_Venta, Tipo_Movimiento, Puntos,
                                    Monto_Afectado, Saldo_Restante, Observacion, USUCRE)
    VALUES (cliente_id, venta_id, 'GANANCIA', v_pts,
            monto, v_sal, 'Acreditación automática por venta', 'sistema');

    RETURN v_pts;
END $$;

/* ================================================================================
   05. CANJEAR PUNTOS (USO) : cada 100 puntos = 1 sol de descuento
   ================================================================================ */
CREATE OR REPLACE FUNCTION sp_canjear_puntos(
    cliente_id    int,
    venta_id      int DEFAULT NULL,
    puntos_usados int DEFAULT 0)
RETURNS numeric(12,2)
LANGUAGE plpgsql
AS $$
DECLARE
    v_bloque  int;
    v_valor   numeric(8,2);
    v_saldo   int;
    v_desc    numeric(12,2);
BEGIN
    SELECT Puntos_X_Descuento, Valor_Descuento
      INTO v_bloque, v_valor
      FROM CONFIG_PUNTOS WHERE ESTADO = 'A';

    SELECT Puntos INTO v_saldo FROM CLIENTE WHERE ID_Cliente = cliente_id;

    IF v_saldo IS NULL THEN
        RAISE EXCEPTION 'Cliente % no existe', cliente_id;
    END IF;
    IF puntos_usados > v_saldo THEN
        RAISE EXCEPTION 'Saldo insuficiente: cliente tiene % puntos, solicita %', v_saldo, puntos_usados;
    END IF;
    IF puntos_usados <= 0 OR puntos_usados % v_bloque <> 0 THEN
        RAISE EXCEPTION 'El canje debe ser múltiplo de % puntos', v_bloque;
    END IF;

    v_desc := floor(puntos_usados::numeric / v_bloque) * v_valor;

    UPDATE CLIENTE
       SET Puntos = Puntos - puntos_usados,
           USUMOD = current_user,
           PCMOD  = left(COALESCE(inet_client_addr()::text, 'supabase'), 30),
           FECMOD = now()
     WHERE ID_Cliente = cliente_id
    RETURNING Puntos INTO v_saldo;

    INSERT INTO TRANSACCION_PUNTOS (ID_Cliente, ID_Venta, Tipo_Movimiento, Puntos,
                                    Monto_Afectado, Saldo_Restante, Observacion, USUCRE)
    VALUES (cliente_id, venta_id, 'USO', -puntos_usados,
            v_desc, v_saldo, 'Canje de puntos por descuento', 'sistema');

    RETURN v_desc;
END $$;

/* ================================================================================
   06. TRIGGER DE AUDITORÍA
   ================================================================================ */
CREATE OR REPLACE FUNCTION fn_auditoria_puntos()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO AUDITORIA (N_Tabla, Accion, ID_Registro, Valor_Nuevo, USUCRE)
    VALUES ('TRANSACCION_PUNTOS', TG_OP, NEW.ID_Transaccion, to_jsonb(NEW)::text, current_user);
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS TR_AUDITORIA_PUNTOS ON TRANSACCION_PUNTOS;
CREATE TRIGGER TR_AUDITORIA_PUNTOS
AFTER INSERT OR UPDATE ON TRANSACCION_PUNTOS
FOR EACH ROW EXECUTE FUNCTION fn_auditoria_puntos();

/* ================================================================================
   07. ACREDITACIÓN AUTOMÁTICA AL REGISTRAR UNA VENTA
   ================================================================================ */
CREATE OR REPLACE FUNCTION fn_venta_acredita_puntos()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.Anulada = 'N' AND NEW.ESTADO = 'A' AND NEW.ID_Cliente IS NOT NULL THEN
        PERFORM sp_acreditar_puntos(NEW.ID_Cliente, NEW.ID_Venta, NEW.Total);
    END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS TR_VENTA_PUNTOS ON VENTA;
CREATE TRIGGER TR_VENTA_PUNTOS
AFTER INSERT ON VENTA
FOR EACH ROW EXECUTE FUNCTION fn_venta_acredita_puntos();

/* ================================================================================
   08. POLÍTICAS RLS (Row Level Security) PARA SUPABASE
       El cliente autenticado solo ve sus propios puntos; el backend con
       service_role administra todo el programa.
   ================================================================================ */
ALTER TABLE TRANSACCION_PUNTOS ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "cliente_lee_sus_puntos" ON TRANSACCION_PUNTOS;
CREATE POLICY "cliente_lee_sus_puntos" ON TRANSACCION_PUNTOS
    FOR SELECT
    USING (
        auth.role() = 'service_role'
        OR ID_Cliente IN (
            SELECT c.ID_Cliente
            FROM CLIENTE c
            WHERE c.UUID_Auth = auth.uid()
        )
    );
