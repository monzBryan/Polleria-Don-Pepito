/* ==================================================================================
   SISTEMA DE GESTIÓN DE VENTAS Y PEDIDOS PARA RESTAURANTE
   Adaptación del modelo SQL Server (01_MODELO_RESTAURANTE_SQLSERVER.sql)
   a PostgreSQL 17 / Supabase.
   ----------------------------------------------------------------------------------
   Equivalencias aplicadas:
     IDENTITY(1,1)      -> GENERATED BY DEFAULT AS IDENTITY
     datetime / date    -> timestamptz / date
     GETDATE()          -> now()
     SUSER_SNAME()      -> current_user
     HOST_NAME()        -> 'supabase'
     ISNULL / + (texto) -> COALESCE / ||
     INT IDENTITY PK    -> PK simple (se elimina la PK duplicada del original)
     Columnas calculadas-> GENERATED ALWAYS AS (...) STORED
   Estándar de auditoría: USUCRE, PCCRE, FECCRE, USUMOD, PCMOD, FECMOD, ESTADO
   Borrado lógico: ESTADO = 'A' Activo / 'I' Inactivo / 'E' Eliminado
   ================================================================================== */

