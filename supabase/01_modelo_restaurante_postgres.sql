/* Total bruto de un pedido: solo líneas activas, no anuladas y no de cortesía */
CREATE OR REPLACE FUNCTION fn_total_pedido(p_id_pedido int)
RETURNS numeric(12,2)
LANGUAGE sql STABLE
AS $$
    SELECT COALESCE(SUM(Sub_Total), 0)::numeric(12,2)
    FROM DETALLE_PEDIDO
    WHERE ID_Pedido = p_id_pedido
      AND Estado_Preparacion <> 'A'
      AND ESTADO = 'A'
      AND Es_Cortesia = 'N';
$$;

/* Login con validación de estado, bloqueo y hash SHA-256 */
CREATE OR REPLACE FUNCTION sp_login(p_logeo varchar, p_clave varchar)
RETURNS TABLE (id_usuario_out int, logeo_out varchar, tipo_usuario_out varchar,
               empleado_out text, cargo_out varchar, mensaje_out text)
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
    v_id   int;
    v_hash varchar(200);
BEGIN
    SELECT u.ID_Usuario, u.Clave INTO v_id, v_hash
    FROM USUARIO u
    WHERE u.Logeo = p_logeo AND u.ESTADO = 'A' AND u.Bloqueado = 'N';

    IF v_id IS NULL THEN
        INSERT INTO AUDITORIA(ID_Usuario, N_Tabla, Accion, Valor_Nuevo)
        VALUES (NULL, 'USUARIO', 'LOGIN_FALLIDO', 'Logeo: ' || p_logeo);

        RETURN QUERY SELECT 0, p_logeo, NULL::varchar, NULL::text, NULL::varchar,
                            'Usuario inexistente, inactivo o bloqueado'::text;
        RETURN;
    END IF;

    IF v_hash <> encode(digest(p_clave, 'sha256'), 'hex') THEN
        UPDATE USUARIO
           SET Intentos = Intentos + 1,
               Bloqueado = CASE WHEN Intentos + 1 >= 3 THEN 'S' ELSE 'N' END,
               USUMOD = current_user,
               PCMOD = 'supabase',
               FECMOD = now()
         WHERE ID_Usuario = v_id;

        INSERT INTO AUDITORIA(ID_Usuario, N_Tabla, Accion, ID_Registro, Valor_Nuevo)
        VALUES (v_id, 'USUARIO', 'LOGIN_FALLIDO', v_id, 'Clave incorrecta');

        RETURN QUERY SELECT 0, p_logeo, NULL::varchar, NULL::text, NULL::varchar,
                            'Clave incorrecta'::text;
        RETURN;
    END IF;

    UPDATE USUARIO
       SET Intentos = 0, F_UltimoAcceso = now()
     WHERE ID_Usuario = v_id;

    INSERT INTO AUDITORIA(ID_Usuario, N_Tabla, Accion, ID_Registro, Valor_Nuevo)
    VALUES (v_id, 'USUARIO', 'LOGIN', v_id, 'Acceso correcto');

    RETURN QUERY
    SELECT u.ID_Usuario, u.Logeo::varchar, tu.N_TipoUsuario::varchar,
           (p.Nombre || ' ' || COALESCE(p.Ap_Paterno, ''))::text,
           c.N_Cargo::varchar, 'Acceso correcto'::text
    FROM USUARIO u
      JOIN TIPO_USUARIO tu ON tu.ID_TipoUsuario = u.ID_TipoUsuario
      JOIN EMPLEADO e      ON e.ID_Empleado     = u.ID_Empleado
      JOIN PERSONA p       ON p.ID_Persona      = e.ID_Persona
      JOIN CARGO c         ON c.ID_Cargo        = e.ID_Cargo
    WHERE u.ID_Usuario = v_id;
END $$;

/* Permisos efectivos de un usuario */
CREATE OR REPLACE FUNCTION sp_permisos_usuario(p_id_usuario int)
RETURNS TABLE (n_modulo varchar, orden int, clave varchar, n_permiso varchar)
LANGUAGE sql STABLE
AS $$
    SELECT m.N_Modulo::varchar, m.Orden, p.Clave::varchar, p.N_Permiso::varchar
    FROM USUARIO_ROL ur
      JOIN ROL_PERMISO rp ON rp.ID_Rol = ur.ID_Rol AND rp.Concedido = 'S' AND rp.ESTADO = 'A'
      JOIN PERMISO p      ON p.ID_Permiso = rp.ID_Permiso AND p.ESTADO = 'A'
      JOIN MODULO m       ON m.ID_Modulo = p.ID_Modulo AND m.ESTADO = 'A'
    WHERE ur.ID_Usuario = p_id_usuario AND ur.Vigente = 'S' AND ur.ESTADO = 'A'
    ORDER BY m.Orden, p.Clave;
$$;

/* Apertura de caja */
CREATE OR REPLACE FUNCTION sp_aperturar_caja(
    p_id_caja int,
    p_id_usuario int,
    p_monto_inicial numeric(12,2),
    p_numero_turno varchar DEFAULT NULL)
RETURNS TABLE (id_apertura_out int, mensaje_out text)
LANGUAGE plpgsql
AS $$
DECLARE
    v_id int;
    v_turno varchar(20);
BEGIN
    IF EXISTS (SELECT 1 FROM APERTURA_CAJA WHERE ID_Caja = p_id_caja AND Situacion = 'A') THEN
        RAISE EXCEPTION 'La caja ya tiene un turno abierto.';
    END IF;

    v_turno := COALESCE(p_numero_turno, to_char(now(), 'YYYYMMDD') || '-' || p_id_caja::text);

    INSERT INTO APERTURA_CAJA(ID_Caja, ID_Usuario, Numero_Turno, Monto_Inicial, Monto_Sistema, Situacion)
    VALUES (p_id_caja, p_id_usuario, v_turno, p_monto_inicial, p_monto_inicial, 'A')
    RETURNING ID_AperturaCaja INTO v_id;

    UPDATE CAJA
       SET Aperturada = 'S', USUMOD = current_user, PCMOD = 'supabase', FECMOD = now()
     WHERE ID_Caja = p_id_caja;

    INSERT INTO AUDITORIA(ID_Usuario, N_Tabla, Accion, ID_Registro, Valor_Nuevo)
    VALUES (p_id_usuario, 'APERTURA_CAJA', 'INSERT', v_id,
            'Apertura con S/ ' || p_monto_inicial::text);

    RETURN QUERY SELECT v_id, 'Caja aperturada correctamente'::text;
END $$;

/* Registro de movimiento de caja */
CREATE OR REPLACE FUNCTION sp_registrar_movimiento_caja(
    p_id_apertura int,
    p_id_concepto int,
    p_id_metodo_pago int,
    p_id_usuario int,
    p_monto numeric(12,2),
    p_descripcion varchar DEFAULT NULL,
    p_id_pedido int DEFAULT NULL,
    p_id_venta int DEFAULT NULL,
    p_numero_operacion varchar DEFAULT NULL,
    p_retornar char DEFAULT 'S')
RETURNS TABLE (id_movimiento_out int, mensaje_out text)
LANGUAGE plpgsql
AS $$
DECLARE
    v_id_tipo int;
    v_signo char(1);
    v_afecta char(1);
    v_id int;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM APERTURA_CAJA WHERE ID_AperturaCaja = p_id_apertura AND Situacion = 'A') THEN
        RAISE EXCEPTION 'El turno de caja no está abierto.';
    END IF;

    SELECT cc.ID_TipoMovimiento, tm.Signo,
           CASE WHEN cc.Afecta_Efectivo = 'S' AND mp.Afecta_Efectivo = 'S' THEN 'S' ELSE 'N' END
      INTO v_id_tipo, v_signo, v_afecta
    FROM CONCEPTO_CAJA cc
      JOIN TIPO_MOVIMIENTO_CAJA tm ON tm.ID_TipoMovimiento = cc.ID_TipoMovimiento
      CROSS JOIN METODO_PAGO mp
    WHERE cc.ID_Concepto = p_id_concepto AND mp.ID_MetodoPago = p_id_metodo_pago;

    INSERT INTO MOVIMIENTO_CAJA(ID_AperturaCaja, ID_TipoMovimiento, ID_Concepto, ID_MetodoPago,
                                ID_Usuario, ID_Pedido, ID_Venta, Numero_Operacion, Descripcion,
                                Monto, Afecta_Efectivo)
    VALUES (p_id_apertura, v_id_tipo, p_id_concepto, p_id_metodo_pago,
            p_id_usuario, p_id_pedido, p_id_venta, p_numero_operacion, p_descripcion,
            p_monto, v_afecta)
    RETURNING ID_MovimientoCaja INTO v_id;

    UPDATE APERTURA_CAJA
       SET Total_Ingresos = Total_Ingresos + CASE WHEN v_signo = '+' THEN p_monto ELSE 0 END,
           Total_Egresos  = Total_Egresos  + CASE WHEN v_signo = '-' THEN p_monto ELSE 0 END,
           Monto_Sistema  = Monto_Sistema  + CASE WHEN v_afecta = 'S'
                                                  THEN CASE WHEN v_signo = '+' THEN p_monto ELSE -p_monto END
                                                  ELSE 0 END,
           USUMOD = current_user, PCMOD = 'supabase', FECMOD = now()
     WHERE ID_AperturaCaja = p_id_apertura;

    RETURN QUERY SELECT v_id, 'Movimiento registrado'::text;
END $$;

/* Cierre y arqueo de caja */
CREATE OR REPLACE FUNCTION sp_cerrar_caja(
    p_id_apertura int,
    p_id_usuario_cierre int,
    p_monto_declarado numeric(12,2),
    p_observacion varchar DEFAULT NULL)
RETURNS TABLE (id_apertura_out int, monto_sistema_out numeric, monto_declarado_out numeric,
               diferencia_out numeric, resultado_out text)
LANGUAGE plpgsql
AS $$
DECLARE
    v_id_caja int;
    v_sistema numeric(12,2);
    v_diferencia numeric(12,2);
BEGIN
    SELECT ID_Caja, Monto_Sistema INTO v_id_caja, v_sistema
    FROM APERTURA_CAJA
    WHERE ID_AperturaCaja = p_id_apertura AND Situacion = 'A';

    IF v_id_caja IS NULL THEN
        RAISE EXCEPTION 'Turno inexistente o ya cerrado.';
    END IF;

    v_diferencia := p_monto_declarado - v_sistema;

    UPDATE APERTURA_CAJA
       SET ID_UsuarioCierre = p_id_usuario_cierre,
           F_Cierre         = now(),
           Monto_Declarado  = p_monto_declarado,
           Diferencia       = v_diferencia,
           Situacion        = 'C',
           Observacion      = p_observacion,
           USUMOD = current_user, PCMOD = 'supabase', FECMOD = now()
     WHERE ID_AperturaCaja = p_id_apertura;

    UPDATE CAJA
       SET Aperturada = 'N', USUMOD = current_user, PCMOD = 'supabase', FECMOD = now()
     WHERE ID_Caja = v_id_caja;

    INSERT INTO AUDITORIA(ID_Usuario, N_Tabla, Accion, ID_Registro, Valor_Nuevo)
    VALUES (p_id_usuario_cierre, 'APERTURA_CAJA', 'UPDATE', p_id_apertura,
            'Cierre. Sistema: ' || v_sistema::text || ' Declarado: ' || p_monto_declarado::text);

    RETURN QUERY
    SELECT ac.ID_AperturaCaja, ac.Monto_Sistema, ac.Monto_Declarado, ac.Diferencia,
           CASE WHEN ac.Diferencia = 0 THEN 'CUADRADO'
                WHEN ac.Diferencia > 0 THEN 'SOBRANTE' ELSE 'FALTANTE' END
    FROM APERTURA_CAJA ac
    WHERE ac.ID_AperturaCaja = p_id_apertura;
END $$;

/* Abrir un pedido / comanda */
CREATE OR REPLACE FUNCTION sp_abrir_pedido(
    p_id_tipo_pedido int,
    p_id_usuario int,
    p_id_mesa int DEFAULT NULL,
    p_id_cliente int DEFAULT NULL,
    p_id_empleado int DEFAULT NULL,
    p_n_comensales int DEFAULT 1,
    p_observacion varchar DEFAULT NULL)
RETURNS TABLE (id_pedido_out int, numero_pedido_out varchar)
LANGUAGE plpgsql
AS $$
DECLARE
    v_req_mesa char(1);
    v_num varchar(15);
    v_id int;
    v_correlativo int;
BEGIN
    SELECT Requiere_Mesa INTO v_req_mesa FROM TIPO_PEDIDO WHERE ID_TipoPedido = p_id_tipo_pedido;

    IF v_req_mesa = 'S' AND p_id_mesa IS NULL THEN
        RAISE EXCEPTION 'El tipo de pedido exige una mesa.';
    END IF;

    IF p_id_mesa IS NOT NULL AND EXISTS (
        SELECT 1
        FROM PEDIDO p
          JOIN ESTADO_PEDIDO ep ON ep.ID_EstadoPedido = p.ID_EstadoPedido
        WHERE p.ID_Mesa = p_id_mesa AND p.Anulado = 'N' AND p.Facturado = 'N'
          AND ep.Descripcion <> 'ANULADO'
    ) THEN
        RAISE EXCEPTION 'La mesa ya tiene una comanda abierta.';
    END IF;

    SELECT COALESCE(MAX(right(Numero_Pedido, 4)::int), 0) + 1 INTO v_correlativo
    FROM PEDIDO
    WHERE Numero_Pedido LIKE 'PED' || to_char(timezone('America/Lima', now()), 'YYYYMMDD') || '%';

    v_num := 'PED' || to_char(timezone('America/Lima', now()), 'YYYYMMDD')
             || lpad(v_correlativo::text, 4, '0');

    INSERT INTO PEDIDO(Numero_Pedido, ID_Cliente, ID_Mesa, ID_TipoPedido, ID_EstadoPedido,
                       ID_Usuario, ID_Empleado, N_Comensales, Observacion)
    VALUES (v_num, p_id_cliente, p_id_mesa, p_id_tipo_pedido, 1,
            p_id_usuario, p_id_empleado, p_n_comensales, p_observacion)
    RETURNING ID_Pedido INTO v_id;

    IF p_id_mesa IS NOT NULL THEN
        UPDATE MESA
           SET ID_EstadoMesa = 2, USUMOD = current_user, PCMOD = 'supabase', FECMOD = now()
         WHERE ID_Mesa = p_id_mesa;
    END IF;

    RETURN QUERY SELECT v_id, v_num;
END $$;

/* Recalcular totales del pedido (IGV 18% incluido en el precio) */
CREATE OR REPLACE FUNCTION sp_recalcular_pedido(p_id_pedido int)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    v_bruto numeric(12,2);
    v_desc  numeric(12,2);
    v_serv  numeric(12,2) := 0;
    v_total numeric(12,2);
    v_igv   numeric(12,2);
BEGIN
    v_bruto := fn_total_pedido(p_id_pedido);

    SELECT Descuento INTO v_desc FROM PEDIDO WHERE ID_Pedido = p_id_pedido;

    SELECT round((v_bruto - COALESCE(v_desc, 0)) * tm.Cargo_Servicio / 100.0, 2)
      INTO v_serv
    FROM PEDIDO p
      LEFT JOIN MESA m       ON m.ID_Mesa = p.ID_Mesa
      LEFT JOIN TIPO_MESA tm ON tm.ID_TipoMesa = m.ID_TipoMesa
    WHERE p.ID_Pedido = p_id_pedido;

    v_serv  := COALESCE(v_serv, 0);
    v_total := v_bruto - COALESCE(v_desc, 0) + v_serv;
    v_igv   := round(v_total - (v_total / 1.18), 2);

    UPDATE PEDIDO
       SET SubTotal = round(v_total / 1.18, 2),
           Servicio = v_serv,
           IGV      = v_igv,
           Total    = v_total,
           USUMOD = current_user, PCMOD = 'supabase', FECMOD = now()
     WHERE ID_Pedido = p_id_pedido;
END $$;

/* Agregar producto a la comanda */
CREATE OR REPLACE FUNCTION sp_agregar_detalle_pedido(
    p_id_pedido int,
    p_id_producto int,
    p_cantidad numeric(10,2),
    p_nota_cocina varchar DEFAULT NULL,
    p_descuento numeric(10,2) DEFAULT 0)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    v_precio numeric(10,2);
BEGIN
    IF EXISTS (SELECT 1 FROM PEDIDO WHERE ID_Pedido = p_id_pedido AND (Facturado = 'S' OR Anulado = 'S')) THEN
        RAISE EXCEPTION 'El pedido está facturado o anulado.';
    END IF;

    SELECT Precio INTO v_precio
    FROM PRODUCTO
    WHERE ID_Producto = p_id_producto AND ESTADO = 'A' AND Disponible = 'S';

    IF v_precio IS NULL THEN
        RAISE EXCEPTION 'Producto no disponible.';
    END IF;

    INSERT INTO DETALLE_PEDIDO(ID_Pedido, ID_Producto, Cantidad, Precio_Unitario, Descuento, Nota_Cocina)
    VALUES (p_id_pedido, p_id_producto, p_cantidad, v_precio, p_descuento, p_nota_cocina);

    PERFORM sp_recalcular_pedido(p_id_pedido);
END $$;

/* Facturar pedido: VENTA + BOLETA/FACTURA + PAGO + MOVIMIENTO_CAJA */
CREATE OR REPLACE FUNCTION sp_facturar_pedido(
    p_id_pedido int,
    p_id_usuario int,
    p_id_apertura int,
    p_tipo_documento char(2),
    p_id_cliente int DEFAULT NULL,
    p_id_metodo_pago int DEFAULT 1,
    p_monto_recibido numeric(12,2) DEFAULT NULL,
    p_referencia varchar DEFAULT NULL)
RETURNS TABLE (id_venta_out int, serie_out char(4), numero_out char(8),
               total_out numeric, vuelto_out numeric)
LANGUAGE plpgsql
AS $$
DECLARE
    v_subtotal numeric(12,2);
    v_desc     numeric(12,2);
    v_serv     numeric(12,2);
    v_igv      numeric(12,2);
    v_total    numeric(12,2);
    v_id_mesa  int;
    v_id_cliente int;
    v_id_empresa int;
    v_id_venta int;
    v_serie    char(4);
    v_correlativo int;
    v_numero   char(8);
    v_id_concepto int;
    v_monto    numeric(12,2);
    v_vuelto   numeric(12,2);
BEGIN
    IF NOT EXISTS (SELECT 1 FROM PEDIDO WHERE ID_Pedido = p_id_pedido AND Facturado = 'N' AND Anulado = 'N') THEN
        RAISE EXCEPTION 'El pedido no existe, ya fue facturado o está anulado.';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM APERTURA_CAJA WHERE ID_AperturaCaja = p_id_apertura AND Situacion = 'A') THEN
        RAISE EXCEPTION 'No hay turno de caja abierto.';
    END IF;

    PERFORM sp_recalcular_pedido(p_id_pedido);

    SELECT SubTotal, Descuento, Servicio, IGV, Total, ID_Mesa, COALESCE(p_id_cliente, ID_Cliente)
      INTO v_subtotal, v_desc, v_serv, v_igv, v_total, v_id_mesa, v_id_cliente
    FROM PEDIDO
    WHERE ID_Pedido = p_id_pedido;

    IF p_tipo_documento = '01' THEN
        SELECT ID_Empresa INTO v_id_empresa FROM CLIENTE WHERE ID_Cliente = v_id_cliente;
        IF v_id_empresa IS NULL THEN
            RAISE EXCEPTION 'Para emitir FACTURA el cliente debe estar asociado a una EMPRESA con RUC.';
        END IF;
    END IF;

    v_monto  := COALESCE(p_monto_recibido, v_total);
    v_vuelto := GREATEST(v_monto - v_total, 0);

    INSERT INTO VENTA(ID_Pedido, ID_Cliente, ID_Usuario, ID_AperturaCaja, TipoDocumento,
                      SubTotal, Descuento, Servicio, IGV, Total, Total_Pagado, Vuelto)
    VALUES (p_id_pedido, v_id_cliente, p_id_usuario, p_id_apertura, p_tipo_documento,
            v_subtotal, v_desc, v_serv, v_igv, v_total, v_monto, v_vuelto)
    RETURNING ID_Venta INTO v_id_venta;

    INSERT INTO DETALLE_VENTA(ID_Venta, ID_Producto, Cantidad, Precio, Descuento)
    SELECT v_id_venta, ID_Producto, Cantidad, Precio_Unitario, Descuento
    FROM DETALLE_PEDIDO
    WHERE ID_Pedido = p_id_pedido AND Estado_Preparacion <> 'A' AND ESTADO = 'A' AND Es_Cortesia = 'N';

    UPDATE SERIE_DOCUMENTO
       SET Correlativo = Correlativo + 1
     WHERE ID_Serie = (SELECT ID_Serie FROM SERIE_DOCUMENTO
                       WHERE Tipo_Documento = p_tipo_documento AND ESTADO = 'A'
                       ORDER BY ID_Serie LIMIT 1)
    RETURNING Serie, Correlativo INTO v_serie, v_correlativo;

    IF v_serie IS NULL THEN
        RAISE EXCEPTION 'No existe serie activa para el tipo de documento indicado.';
    END IF;

    v_numero := lpad(v_correlativo::text, 8, '0');

    IF p_tipo_documento = '03' THEN
        INSERT INTO BOLETA(ID_Venta, Serie, Numero, Cliente_Documento, Cliente_Nombre)
        SELECT v_id_venta, v_serie, v_numero, p.N_Documento,
               trim(p.Nombre || ' ' || COALESCE(p.Ap_Paterno, '') || ' ' || COALESCE(p.Ap_Materno, ''))
        FROM CLIENTE c
          LEFT JOIN PERSONA p ON p.ID_Persona = c.ID_Persona
        WHERE c.ID_Cliente = v_id_cliente;
    ELSIF p_tipo_documento = '01' THEN
        INSERT INTO FACTURA(ID_Venta, ID_Empresa, Serie, Numero)
        VALUES (v_id_venta, v_id_empresa, v_serie, v_numero);
    END IF;

    INSERT INTO PAGO_VENTA(ID_Venta, ID_MetodoPago, Monto, Referencia)
    VALUES (v_id_venta, p_id_metodo_pago, v_total, p_referencia);

    SELECT CASE WHEN Afecta_Efectivo = 'S' THEN 1
                WHEN N_MetodoPago IN ('YAPE','PLIN') THEN 3
                ELSE 2 END
      INTO v_id_concepto
    FROM METODO_PAGO WHERE ID_MetodoPago = p_id_metodo_pago;

    PERFORM sp_registrar_movimiento_caja(
        p_id_apertura, v_id_concepto, p_id_metodo_pago, p_id_usuario,
        v_total, 'Cobro comprobante', p_id_pedido, v_id_venta, p_referencia, 'N');

    UPDATE PEDIDO
       SET Facturado = 'S', ID_EstadoPedido = 4, F_Cierre = now(),
           USUMOD = current_user, PCMOD = 'supabase', FECMOD = now()
     WHERE ID_Pedido = p_id_pedido;

    IF v_id_mesa IS NOT NULL THEN
        UPDATE MESA
           SET ID_EstadoMesa = 1, USUMOD = current_user, PCMOD = 'supabase', FECMOD = now()
         WHERE ID_Mesa = v_id_mesa;
    END IF;

    INSERT INTO AUDITORIA(ID_Usuario, N_Tabla, Accion, ID_Registro, Valor_Nuevo)
    VALUES (p_id_usuario, 'VENTA', 'INSERT', v_id_venta,
            'Comprobante ' || v_serie || '-' || v_numero || ' por S/ ' || v_total::text);

    RETURN QUERY SELECT v_id_venta, v_serie, v_numero, v_total, v_vuelto;
END $$;

/* Anular pedido */
CREATE OR REPLACE FUNCTION sp_anular_pedido(
    p_id_pedido int,
    p_id_usuario int,
    p_motivo varchar)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    v_id_mesa int;
BEGIN
    IF EXISTS (SELECT 1 FROM PEDIDO WHERE ID_Pedido = p_id_pedido AND Facturado = 'S') THEN
        RAISE EXCEPTION 'El pedido ya fue facturado. Use nota de crédito.';
    END IF;

    SELECT ID_Mesa INTO v_id_mesa FROM PEDIDO WHERE ID_Pedido = p_id_pedido;

    UPDATE PEDIDO
       SET Anulado = 'S', ID_EstadoPedido = 5, Motivo_Anulacion = p_motivo, ESTADO = 'I',
           USUMOD = current_user, PCMOD = 'supabase', FECMOD = now()
     WHERE ID_Pedido = p_id_pedido;

    UPDATE DETALLE_PEDIDO
       SET Estado_Preparacion = 'A', ESTADO = 'I',
           USUMOD = current_user, PCMOD = 'supabase', FECMOD = now()
     WHERE ID_Pedido = p_id_pedido;

    IF v_id_mesa IS NOT NULL THEN
        UPDATE MESA
           SET ID_EstadoMesa = 1, USUMOD = current_user, PCMOD = 'supabase', FECMOD = now()
         WHERE ID_Mesa = v_id_mesa;
    END IF;

    INSERT INTO AUDITORIA(ID_Usuario, N_Tabla, Accion, ID_Registro, Valor_Nuevo)
    VALUES (p_id_usuario, 'PEDIDO', 'ANULAR', p_id_pedido, p_motivo);
END $$;

/* ==================================================================================
   TRIGGERS DE AUDITORÍA
   ================================================================================== */

CREATE OR REPLACE FUNCTION fn_producto_auditoria()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_accion varchar(20);
    v_id int;
BEGIN
    v_accion := TG_OP;
    v_id := COALESCE(NEW.ID_Producto, OLD.ID_Producto);

    INSERT INTO AUDITORIA(N_Tabla, Accion, ID_Registro, Valor_Anterior, Valor_Nuevo)
    VALUES ('PRODUCTO', v_accion, v_id,
            CASE WHEN TG_OP IN ('UPDATE','DELETE')
                 THEN 'Producto=' || OLD.N_Producto || '|Precio=' || OLD.Precio || '|Estado=' || OLD.ESTADO
            END,
            CASE WHEN TG_OP IN ('INSERT','UPDATE')
                 THEN 'Producto=' || NEW.N_Producto || '|Precio=' || NEW.Precio || '|Estado=' || NEW.ESTADO
            END);
    RETURN COALESCE(NEW, OLD);
END $$;

DROP TRIGGER IF EXISTS TR_PRODUCTO_AUDITORIA ON PRODUCTO;
CREATE TRIGGER TR_PRODUCTO_AUDITORIA
AFTER INSERT OR UPDATE OR DELETE ON PRODUCTO
FOR EACH ROW EXECUTE FUNCTION fn_producto_auditoria();

CREATE OR REPLACE FUNCTION fn_venta_auditoria()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.Total <> OLD.Total OR NEW.Anulada <> OLD.Anulada THEN
        INSERT INTO AUDITORIA(ID_Usuario, N_Tabla, Accion, ID_Registro, Valor_Anterior, Valor_Nuevo)
        VALUES (NEW.ID_Usuario, 'VENTA', 'UPDATE', NEW.ID_Venta,
                'Total=' || OLD.Total || '|Anulada=' || OLD.Anulada,
                'Total=' || NEW.Total || '|Anulada=' || NEW.Anulada);
    END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS TR_VENTA_AUDITORIA ON VENTA;
CREATE TRIGGER TR_VENTA_AUDITORIA
AFTER UPDATE ON VENTA
FOR EACH ROW EXECUTE FUNCTION fn_venta_auditoria();

